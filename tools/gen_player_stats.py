#!/usr/bin/env python3
"""Generate include/game/player_stats_gen.h from the cooked stat structs.

AA_SteamStatManager replicates two custom structs (doc sec 13/23):
AA_MP_PlayerMatchStatistics (12 fields) and AA_MP_PlayerStatistics (116).
This emits, for each, a C++ struct with one typed member per field (named
exactly as in UnrealScript) plus a field table {name, kind, offset} so the
wire encoder and the JSON stats export walk the same single definition --
no hand-transcribed field lists.

Usage (from repo root):
  aa3-linux-server/tools/gen_player_stats.py \
      --tool aa3-linux-server/build/aa3_build_manifests --pkg-dir clean_packages \
      --out aa3-linux-server/include/game/player_stats_gen.h
"""
import argparse
import re
import subprocess
import sys

STRUCTS = [("PlayerMatchStats", "AA_MP_PlayerMatchStatistics"),
           ("PlayerRoundStats", "AA_MP_PlayerStatistics")]
CTYPE = {"Bool": ("bool", "kBool"), "Float": ("float", "kFloat"),
         "Int": ("int32_t", "kInt"), "Byte": ("uint8_t", "kByte")}


def fields(tool, pkg_dir, struct):
    out = subprocess.run([tool, "--struct-layout", f"{pkg_dir}/AA3Baseline.u", struct,
                          "--pkg-dir", pkg_dir], capture_output=True, text=True).stdout
    rows = re.findall(r"^\s+\[0\] \S+?\.(\S+)\s+(\w+)Property(\s+\S+)?", out, re.M)
    for name, typ, sub in rows:
        if typ not in CTYPE or (typ == "Byte" and sub.strip().startswith("E")):
            sys.exit(f"{struct}.{name}: unsupported type {typ}{sub} (regenerate by hand?)")
    return [(n, t) for n, t, _ in rows]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tool", required=True)
    ap.add_argument("--pkg-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    L = ["// GENERATED by tools/gen_player_stats.py from `--struct-layout` on",
         "// AA3Baseline.u's stat structs. DO NOT EDIT BY HAND -- regenerate.",
         "// Declaration order == wire order (custom-struct NetSerializeItem walks",
         "// fields positionally with no per-field index, doc sec 11.1).",
         "#ifndef AA3_GAME_PLAYER_STATS_GEN_H",
         "#define AA3_GAME_PLAYER_STATS_GEN_H",
         "",
         "#include <cstddef>",
         "#include <cstdint>",
         "",
         "namespace aa3 {",
         "namespace game {",
         "",
         "enum class StatKind : uint8_t { kBool, kFloat, kInt, kByte };",
         "struct StatField { const char* name; StatKind kind; size_t offset; };",
         ""]
    for cname, struct in STRUCTS:
        fl = fields(a.tool, a.pkg_dir, struct)
        L.append(f"// AA3Baseline.{struct} ({len(fl)} fields)")
        L.append(f"struct {cname} {{")
        for n, t in fl:
            L.append(f"    {CTYPE[t][0]} {n} = {'false' if t == 'Bool' else '0'};")
        L.append(f"    static constexpr size_t kNumFields = {len(fl)};")
        L.append("};")
        L.append(f"inline const StatField* {cname}Fields() {{")
        L.append("    static const StatField f[] = {")
        for n, t in fl:
            L.append(f'        {{"{n}", StatKind::{CTYPE[t][1]}, offsetof({cname}, {n})}},')
        L.append("    };")
        L.append("    return f;")
        L.append("}")
        L.append("")
    L += ["}  // namespace game", "}  // namespace aa3", "",
          "#endif  // AA3_GAME_PLAYER_STATS_GEN_H", ""]
    open(a.out, "w").write("\n".join(L))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
