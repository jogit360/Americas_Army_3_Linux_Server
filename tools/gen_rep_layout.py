#!/usr/bin/env python3
"""Generate include/network/rep_layout_gen.h from `aa3_build_manifests --rep-layout`.

Every RepIndex/MaxIndex the server writes on the wire comes from here, by
field NAME, instead of hand-typed numbers in the encoders. Hand-typed indices
are how the FUNC_Net bit bug (doc sec 19) shifted every table silently: fix
the tool, rerun this, rebuild -- the encoders follow automatically.

Usage (from repo root):
  aa3-linux-server/tools/gen_rep_layout.py \
      --tool aa3-linux-server/build/aa3_build_manifests \
      --pkg-dir clean_packages \
      --out aa3-linux-server/include/network/rep_layout_gen.h
"""
import argparse
import re
import subprocess
import sys

# (namespace in header, package file, class name)
CLASSES = [
    ("WorldInfo",              "Engine.u",      "WorldInfo"),
    ("GRI",                    "AA3Baseline.u", "AA_GameReplicationInfo"),
    ("TeamInfo",               "AA3Baseline.u", "AA_TeamInfo"),
    ("PRI",                    "AA3Baseline.u", "AA_PlayerReplicationInfo"),
    ("PC",                     "AA3Baseline.u", "AA_PlayerController"),
    ("AGP_PC",                 "AA3Game.u",     "AGP_PlayerController"),
    ("Pawn",                   "AA3Baseline.u", "AA_Pawn"),
    ("SteamStatManager",       "AA3Baseline.u", "AA_SteamStatManager"),
    ("MOSQualificationBCT",    "AA3Baseline.u", "AA_MOSQualificationBCT"),
    ("PlayerStorageProxy",     "AA3Baseline.u", "AA_PlayerStorageProxy"),
    ("ES2Manager",             "AA3Baseline.u", "AA_ES2Manager"),
    ("FireTeamInfo",           "AA3Baseline.u", "AA_FireTeamInfo"),
    ("ClassRoleRI",            "AA3Baseline.u", "AA_MCClassRoleReplicationInfo"),
]

ROW = re.compile(r"^\s+(\d+)\s+(\S+)\s+.*?(\w+)\.(\w+)(\(\))?(\[\])?(?:\s+(server|client)\s+(reliable|unreliable))?")


def dump(tool, pkg_dir, pkg, cls):
    out = subprocess.run([tool, "--rep-layout", f"{pkg_dir}/{pkg}", cls, "--pkg-dir", pkg_dir],
                         capture_output=True, text=True).stdout
    m = re.search(r"^\s+MaxIndex=(\d+)", out, re.M)
    if not m:
        sys.exit(f"no MaxIndex for {cls} in {pkg}:\n{out[-2000:]}")
    rows = []
    in_table = False
    for line in out.splitlines():
        if "Flattened wire fields" in line:
            in_table = True
            continue
        if not in_table:
            continue
        r = ROW.match(line)
        if r:
            rows.append((int(r[1]), r[2], r[3], r[4], r[5], r[6], r[7], r[8]))
    return int(m[1]), rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tool", required=True)
    ap.add_argument("--pkg-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    L = ["// GENERATED by tools/gen_rep_layout.py from `aa3_build_manifests --rep-layout`.",
         "// DO NOT EDIT BY HAND -- regenerate instead (see the script's docstring).",
         "// Each namespace = one replicated class: kMaxIndex (the WriteIntWrapped",
         "// bound) plus one constant per net field, named after the UnrealScript",
         "// field. Functions (RPCs) carry a trailing comment with direction and",
         "// reliability decoded from AA3's FUNC_* bits (doc sec 19).",
         "#ifndef AA3_NETWORK_REP_LAYOUT_GEN_H",
         "#define AA3_NETWORK_REP_LAYOUT_GEN_H",
         "",
         "#include <cstdint>",
         "",
         "namespace aa3 {",
         "namespace network {",
         "namespace rep {",
         ""]
    for ns, pkg, cls in CLASSES:
        mx, rows = dump(a.tool, a.pkg_dir, pkg, cls)
        L.append(f"// {pkg} {cls}")
        L.append(f"namespace {ns} {{")
        L.append(f"constexpr uint32_t kMaxIndex = {mx};")
        seen = set()
        for idx, typ, decl, name, is_fn, is_arr, direction, rel in rows:
            ident = name if name not in seen else f"{decl}_{name}"
            seen.add(name)
            note = f"{decl}.{name}"
            if is_fn:
                note += f"()  {direction} {rel}"
            else:
                note += f"  {typ}{'[]' if is_arr else ''}"
            L.append(f"constexpr uint32_t {ident} = {idx};  // {note}")
        L.append(f"}}  // namespace {ns}")
        L.append("")
    L += ["}  // namespace rep", "}  // namespace network", "}  // namespace aa3", "",
          "#endif  // AA3_NETWORK_REP_LAYOUT_GEN_H", ""]
    with open(a.out, "w") as f:
        f.write("\n".join(L))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
