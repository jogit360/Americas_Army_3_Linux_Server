#!/usr/bin/env python3
"""Generate include/network/ssc_keystream_gen.h: the 8192-byte AA3 "SSC"
keystream for the ACPU body key (doc sec 24).

SSC (libaa3.dll ssc_encrypt @0x63178110) XORs data with a keystream that
depends only on the key and two .rdata tables, so for the one fixed key the
LAN details protocol uses it can be precomputed — the server needs no game
DLL at runtime. Needs the aa3-backend tools venv (pefile) and libaa3.dll:

  aa3-backend/tools/.venv/bin/python aa3-linux-server/tools/gen_ssc_keystream.py \
      --out aa3-linux-server/include/network/ssc_keystream_gen.h
"""
import argparse, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "aa3-backend", "tools"))
import aa3_acpu, ssc

ap = argparse.ArgumentParser(); ap.add_argument("--out", required=True); a = ap.parse_args()
ks = ssc.keystream(aa3_acpu.BODYKEY, 8192)
L = ["// GENERATED by tools/gen_ssc_keystream.py -- DO NOT EDIT.",
     "// SSC keystream for ACPU body key \"c6mw4it2kg7sz5o0813d9qyufenhj\\0\" (len 30).",
     "#ifndef AA3_NETWORK_SSC_KEYSTREAM_GEN_H", "#define AA3_NETWORK_SSC_KEYSTREAM_GEN_H", "",
     "#include <cstdint>", "", "namespace aa3 {", "namespace network {", "",
     "inline constexpr uint8_t kAcpuBodyKeystream[8192] = {"]
for i in range(0, 8192, 16):
    L.append("    " + ", ".join(f"0x{b:02x}" for b in ks[i:i+16]) + ",")
L += ["};", "", "}  // namespace network", "}  // namespace aa3", "",
      "#endif  // AA3_NETWORK_SSC_KEYSTREAM_GEN_H", ""]
open(a.out, "w").write("\n".join(L)); print("wrote", a.out)
